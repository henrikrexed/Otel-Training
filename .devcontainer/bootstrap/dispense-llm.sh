#!/usr/bin/env bash
# dispense-llm.sh — mint a short-lived LLM proxy credential for the workshop and
# wire opencode to it. Ported from henrikrexed/dynatrace-AI-Agent-Workshop (the
# reference uses node to parse the response; here we bake jq via apt instead).
#
# The facilitator runs a LiteLLM proxy plus a tiny "dispenser" HTTP endpoint.
# Each attendee's Codespace calls the dispenser ONCE with the shared room
# password and gets back a per-attendee virtual key scoped to a server-side
# budget. We never set or even see that budget — it is enforced on the remote
# LiteLLM. All this script does is fetch the credential and point opencode at it.
#
# Graceful-skip contract (same shape as the Dynatrace / GitLab paths):
#   - Needs WORKSHOP_DISPENSER_URL and WORKSHOP_ROOM_PASSWORD. If either is
#     absent we warn, skip, and exit 0 — bring-up continues, the opencode AI
#     steps are simply unavailable. This is the expected state outside a workshop.
#   - Idempotent: re-running re-mints and rewrites the env file + opencode config.
#   - Non-fatal: any failure (bad password, host down, odd response) warns and
#     exits 0 so it never blocks the rest of postCreate.
#   - The minted key is written only to a gitignored, 0600 file (and referenced
#     by opencode via {env:...}, never embedded) and is masked in every log line.
set -uo pipefail

log() { echo "==> dispense-llm: $*"; }

REPO_ROOT="$(git -C "$(dirname "${BASH_SOURCE[0]}")" rev-parse --show-toplevel 2>/dev/null || pwd)"
LLM_ENV_FILE="${WORKSHOP_LLM_ENV_FILE:-$REPO_ROOT/.workshop-llm.env}"
OPENCODE_CONFIG_DIR="${OPENCODE_CONFIG_DIR:-$HOME/.config/opencode}"
OPENCODE_CONFIG="$OPENCODE_CONFIG_DIR/opencode.json"
DEFAULT_MODEL="${WORKSHOP_LLM_DEFAULT_MODEL:-deepseek-chat}"
MAX_TIME="${WORKSHOP_DISPENSER_TIMEOUT:-30}"

# --- Graceful skip when the workshop secrets are not present ------------------
if [[ -z "${WORKSHOP_DISPENSER_URL:-}" || -z "${WORKSHOP_ROOM_PASSWORD:-}" ]]; then
  log "WORKSHOP_DISPENSER_URL / WORKSHOP_ROOM_PASSWORD not set — skipping LLM dispense."
  log "The opencode AI steps (advanced Step 1) will be unavailable until these are set."
  log "This is expected outside the facilitated workshop. Nothing else is affected."
  exit 0
fi

# --- Call the dispenser -------------------------------------------------------
# -s quiet, -o body-to-tmp, -w prints the HTTP status. On a connection failure
# curl prints "000" via -w and exits non-zero; we swallow that and treat an
# empty/odd status as 000 (host down) below.
body="$(mktemp)"
trap 'rm -f "$body"' EXIT

log "requesting an LLM credential from the dispenser (timeout ${MAX_TIME}s)…"
code="$(curl -s -o "$body" -w '%{http_code}' --max-time "$MAX_TIME" \
         -H "X-Room-Password: $WORKSHOP_ROOM_PASSWORD" \
         "$WORKSHOP_DISPENSER_URL" 2>/dev/null)" || true
code="${code:-000}"

case "$code" in
  200)
    : # success — parse below
    ;;
  401)
    log "WARN: dispenser returned 401 — WORKSHOP_ROOM_PASSWORD is wrong."
    log "WARN: get the current room password from the facilitator and re-run:"
    log "WARN:   bash .devcontainer/bootstrap/dispense-llm.sh"
    exit 0
    ;;
  000)
    log "WARN: could not reach the dispenser at WORKSHOP_DISPENSER_URL"
    log "WARN: (host down / network blocked / timed out after ${MAX_TIME}s)."
    log "WARN: this is normal before the facilitator brings the dispenser up; re-run later:"
    log "WARN:   bash .devcontainer/bootstrap/dispense-llm.sh"
    exit 0
    ;;
  *)
    log "WARN: dispenser returned HTTP ${code}. Response body:"
    sed 's/^/    /' "$body" >&2 || true
    log "WARN: skipping (non-fatal)."
    exit 0
    ;;
esac

# --- Parse the response with jq ----------------------------------------------
proxy_url="$(jq -r '.proxy_url // empty' "$body" 2>/dev/null || true)"
virtual_key="$(jq -r '.virtual_key // empty' "$body" 2>/dev/null || true)"
model="$(jq -r '.model // empty' "$body" 2>/dev/null || true)"

if [[ -z "$proxy_url" || -z "$virtual_key" ]]; then
  log "WARN: dispenser returned 200 but the body is missing proxy_url/virtual_key."
  log "WARN: (could not parse it with jq). Skipping (non-fatal)."
  exit 0
fi
model="${model:-$DEFAULT_MODEL}"

# Normalise the proxy base URL to end with /v1 (OpenAI-compatible route).
base_url="${proxy_url%/}"
case "$base_url" in
  */v1) : ;;
  *) base_url="${base_url}/v1" ;;
esac

# --- Write the gitignored credential file (0600) ------------------------------
# umask 077 guards the window between create and chmod; chmod 600 is explicit.
umask 077
cat > "$LLM_ENV_FILE" <<EOF
# Generated by .devcontainer/bootstrap/dispense-llm.sh — DO NOT COMMIT.
# This file is gitignored. It holds a per-attendee workshop LLM proxy key.
# Regenerate at any time with: bash .devcontainer/bootstrap/dispense-llm.sh
export WORKSHOP_LLM_PROXY_URL="$base_url"
export WORKSHOP_LLM_KEY="$virtual_key"
export WORKSHOP_LLM_MODEL="$model"
# OpenAI-compatible aliases so any OpenAI SDK / opencode picks the proxy up.
export OPENAI_BASE_URL="$base_url"
export OPENAI_API_KEY="$virtual_key"
EOF
chmod 600 "$LLM_ENV_FILE"

# --- Configure opencode (runtime) ---------------------------------------------
# An OpenAI-compatible provider pointed at the proxy. The key is NOT written
# here — opencode resolves {env:...} at launch from the sourced env file, so the
# secret lives only in the 0600 file. "build" is opencode's default primary
# agent (it can edit files), which is what the instrumentation lab needs — so we
# leave the agent default alone and only wire provider + model.
mkdir -p "$OPENCODE_CONFIG_DIR"
cat > "$OPENCODE_CONFIG" <<EOF
{
  "\$schema": "https://opencode.ai/config.json",
  "model": "workshop/$model",
  "provider": {
    "workshop": {
      "npm": "@ai-sdk/openai-compatible",
      "name": "Workshop LiteLLM proxy",
      "options": {
        "baseURL": "{env:OPENAI_BASE_URL}",
        "apiKey": "{env:OPENAI_API_KEY}"
      },
      "models": {
        "$model": { "name": "$model (workshop proxy)" }
      }
    }
  }
}
EOF

# --- Make new terminals pick up the proxy -------------------------------------
# Source the env file from ~/.bashrc (idempotent — keyed on the file path).
BASHRC="${BASHRC:-$HOME/.bashrc}"
if ! grep -qF "$LLM_ENV_FILE" "$BASHRC" 2>/dev/null; then
  printf '\n# workshop LLM proxy credential (dispense-llm.sh)\n[ -f %q ] && . %q\n' \
    "$LLM_ENV_FILE" "$LLM_ENV_FILE" >> "$BASHRC"
fi

log "LLM proxy wired: model='${model}'  base='${base_url}'  key=(len=${#virtual_key}, masked)"
log "opencode configured at ${OPENCODE_CONFIG} (provider 'workshop', build mode default)."
log "New terminals pick up the proxy via ~/.bashrc. In THIS shell, run:"
log "  source \"${LLM_ENV_FILE}\""
exit 0
